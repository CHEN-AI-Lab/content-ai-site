const allMessages: Record<string, Messages> = { 'zh-CN': zhCN, 'en': en }

/** Get messages for a given locale. */
export function getMessagesForLocale(locale: string): Messages {
  return allMessages[locale] ?? allMessages[DEFAULT_LOCALE]
}

/** Validate and resolve locale string. */
export function resolveLocale(locale: string | undefined | null): string {
  if (locale && LOCALES.includes(locale as 'zh-CN' | 'en')) return locale
  return DEFAULT_LOCALE
}
